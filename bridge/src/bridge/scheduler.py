"""Proactive follow-up scheduler with injectable virtual clock (M1.12).

The scheduler manages durable timers for SLA-driven nudges and escalation, with an
injectable virtual clock for time-warp testing (frontend Theater mode). Timers are
keyed by ``context_id`` (and optionally ``task_id``); the SLA policy (deadline /
cadence / max_nudges) is read from the skill policy (M1.3).

Two-tier architecture (mirroring ledger / disposition / requirements):
- **Pure core** (this module): ``VirtualClock``, ``Timer``, ``TimerKind``,
  ``plan_followups`` (the SLA engine), ``followup_status`` (the read-model).
- **Adapter impl**: ``bridge.adapters.local.scheduler.LocalScheduler`` (in-memory
  timer store implementing the seam over these types).

Exactly-once invariant (docs/lessons-learned.md A7 — CRITICAL):
``due(now)`` marks each returned timer ``fired`` IN PLACE before returning. The
no-duplicate guarantee rides on this invariant — a fired timer NEVER re-appears in
a subsequent ``due()`` call. The ``Timer`` model is a mutable ``@dataclass`` to
permit this in-place mutation (frozen Pydantic would block it).

Deterministic ordering (lessons-learned.md A5):
``due()`` output is sorted by ``(fire_at, sequence, id)`` — no timestamp. The
virtual clock is an integer counter ("ticks"), not a datetime, keeping everything
deterministic and matching the frontend time-warp story.

See:
- wiki/bridge-proactive.md (SLA ladder, overdue → escalated, read-model projection)
- wiki/bridge-seams.md (Scheduler seam)
- docs/lessons-learned.md C1 (address policy: deadline 3 / cadence 2 / max_nudges 2)

Import discipline: imports ``contract`` (if needed) + ``bridge.skills`` (types only)
+ stdlib/Pydantic. Never imports ``agents``, ``seams``, or ``adapters``. Keep this
module OUT of ``bridge/__init__.py`` (preserve cheap ``import bridge`` + the
no-agents-guard clarity).

Note: "Durable" in M1.12 describes the **seam concept** — the local adapter is
in-memory; restart-durability of the timer store is the Sprint-2 GCP adapter (Cloud
Tasks; A7 "deletion is the fired signal"), analogous to the local/Database split for
Sessions/Task-store (M1.2).
"""

